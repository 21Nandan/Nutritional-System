import React, { useCallback, useEffect, useState } from 'react';
import { Database, AlertTriangle } from 'lucide-react';
import { apiFetch } from '../api';

const SOURCES = [
  {
    name: 'EATGOOD demo catalogue',
    use: 'Products you can browse and compare',
    licence: 'Generated by this project (MIT)',
    note: 'Synthetic: real product names, randomly generated nutrition values, ingredients, allergens and barcodes.',
  },
  {
    name: 'Open Food Facts',
    use: 'Barcode lookups and search results marked "Open Food Facts"; 38 product photos',
    licence: 'Database: ODbL 1.0 · Photos: CC BY-SA',
    note: 'Community-contributed and not checked by EATGOOD.',
    href: 'https://world.openfoodfacts.org',
  },
  {
    name: 'WHO SEARO nutrient profile model (2017), WHO guidance on sugar-sweetened beverages, FSSAI draft Indian Nutrition Rating, Codex labelling guidelines',
    use: 'Category thresholds used for grades and red values',
    licence: 'Public documents; thresholds are informed by them, not endorsed by them',
    note: 'See the standards list on each assessment for the exact numbers used.',
  },
];

export default function DataAuditPage() {
  const [audit, setAudit] = useState(null);
  const [error, setError] = useState(null);

  const load = useCallback(() => {
    setError(null);
    apiFetch('/api/audit')
      .then(setAudit)
      .catch((err) => setError(err.message));
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  return (
    <div className="data-audit-page">
      <div style={{ marginBottom: 28 }}>
        <h1 style={{ fontSize: '2.2rem', color: 'var(--color-primary)', marginBottom: 8, display: 'flex', gap: 10, alignItems: 'center' }}>
          <Database size={28} aria-hidden="true" /> About the data
        </h1>
        <p style={{ color: 'var(--color-text-muted)', fontSize: '0.95rem', maxWidth: 760 }}>
          Where EATGOOD&apos;s information comes from, how reliable it is, and what the data-quality checks found.
          The numbers below are computed from the data files when the server starts.
        </p>
      </div>

      {error && (
        <div role="alert" className="card" style={{ marginBottom: 24, color: '#c62828' }}>
          <p style={{ marginBottom: 10 }}>We couldn&apos;t load the data report: {error}</p>
          <button className="btn-primary" onClick={load}>Try again</button>
        </div>
      )}
      {!audit && !error && (
        <div style={{ padding: '60px 0', textAlign: 'center', color: 'var(--color-text-muted)' }}>Loading data report…</div>
      )}

      {audit && (
        <>
          {audit.dataset.provenance === 'synthetic' && (
            <div className="card" role="note" style={{ marginBottom: 24, borderColor: 'var(--color-warning)', background: 'var(--color-warning-bg)' }}>
              <h2 style={{ fontSize: '1.15rem', color: '#7a3300', display: 'flex', gap: 8, alignItems: 'center', marginBottom: 6 }}>
                <AlertTriangle size={20} aria-hidden="true" /> The catalogue is demo data
              </h2>
              <p style={{ color: '#7a3300', fontSize: '0.9rem' }}>{audit.dataset.provenance_note}</p>
              <p style={{ color: '#7a3300', fontSize: '0.85rem', marginTop: 6 }}>
                Dataset version {audit.dataset.dataset_version} · {audit.dataset.catalogue_rows} products ·{' '}
                {audit.dataset.products_with_images} with a photo · {audit.dataset.categories.length} categories.
                Barcode lookups of real products use Open Food Facts instead.
              </p>
            </div>
          )}

          <div className="card" style={{ marginBottom: 24 }}>
            <h2 style={{ fontSize: '1.25rem', color: 'var(--color-primary)', marginBottom: 16 }}>Sources and licences</h2>
            <div className="responsive-table-wrapper">
              <table style={{ width: '100%', borderCollapse: 'collapse', textAlign: 'left', fontSize: '0.88rem' }}>
                <thead>
                  <tr style={{ background: 'var(--color-surface-alt)', borderBottom: '2px solid var(--color-border)' }}>
                    <th scope="col" style={{ padding: '10px 14px' }}>Source</th>
                    <th scope="col" style={{ padding: '10px 14px' }}>Used for</th>
                    <th scope="col" style={{ padding: '10px 14px' }}>Licence</th>
                    <th scope="col" style={{ padding: '10px 14px' }}>Reliability</th>
                  </tr>
                </thead>
                <tbody>
                  {SOURCES.map((src) => (
                    <tr key={src.name} style={{ borderBottom: '1px solid var(--color-border)' }}>
                      <td style={{ padding: '12px 14px', fontWeight: 600 }}>
                        {src.href ? <a href={src.href} target="_blank" rel="noreferrer">{src.name}</a> : src.name}
                      </td>
                      <td style={{ padding: '12px 14px' }}>{src.use}</td>
                      <td style={{ padding: '12px 14px' }}>{src.licence}</td>
                      <td style={{ padding: '12px 14px', color: 'var(--color-text-muted)' }}>{src.note}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>

          <div className="card" style={{ marginBottom: 24 }}>
            <h2 style={{ fontSize: '1.25rem', color: 'var(--color-primary)', marginBottom: 6 }}>Data-quality checks</h2>
            <p style={{ fontSize: '0.85rem', color: 'var(--color-text-muted)', marginBottom: 14 }}>
              In the demo catalogue some of these problems were inserted on purpose to exercise the checks.
            </p>
            <div className="responsive-table-wrapper">
              <table style={{ width: '100%', borderCollapse: 'collapse', textAlign: 'left', fontSize: '0.88rem' }}>
                <thead>
                  <tr style={{ background: 'var(--color-surface-alt)', borderBottom: '2px solid var(--color-border)' }}>
                    <th scope="col" style={{ padding: '10px 14px' }}>Check</th>
                    <th scope="col" style={{ padding: '10px 14px' }}>Products</th>
                    <th scope="col" style={{ padding: '10px 14px' }}>Share</th>
                    <th scope="col" style={{ padding: '10px 14px' }}>How EATGOOD handles it</th>
                  </tr>
                </thead>
                <tbody>
                  {audit.quality_summary.map((row) => (
                    <tr key={row.Metric} style={{ borderBottom: '1px solid var(--color-border)' }}>
                      <td style={{ padding: '12px 14px', fontWeight: 600 }}>{row.Metric}</td>
                      <td style={{ padding: '12px 14px' }}>{row.Count}</td>
                      <td style={{ padding: '12px 14px' }}>{row.Percentage}</td>
                      <td style={{ padding: '12px 14px', color: 'var(--color-text-muted)' }}>{row['Evaluation Status']}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>

          <div style={{ background: '#fff', border: '1px solid var(--color-border)', borderRadius: 12, padding: 20 }}>
            <h2 style={{ fontSize: '1rem', color: 'var(--color-primary)', marginBottom: 8 }}>Rules EATGOOD follows</h2>
            <ul style={{ margin: 0, paddingLeft: 20, fontSize: '0.85rem', color: 'var(--color-text-muted)', lineHeight: 1.6 }}>
              <li>A missing value is shown as &ldquo;Not stated&rdquo; and is never treated as zero.</li>
              <li>Products with missing allergen information are never suggested as alternatives to people who listed allergens.</li>
              <li>Values read from a label photo must be confirmed by you before anything is scored.</li>
              <li>Photos are matched by product name only and have not been checked against the pack.</li>
            </ul>
          </div>
        </>
      )}
    </div>
  );
}
